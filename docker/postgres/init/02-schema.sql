-- Esquema oficial del proyecto
CREATE SCHEMA IF NOT EXISTS woolfandfox;

-- Tipos enumerados del sistema
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_type t
        JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE t.typname = 'rol_sistema_enum'
          AND n.nspname = 'woolfandfox'
    ) THEN
        CREATE TYPE woolfandfox.rol_sistema_enum AS ENUM ('admin', 'administrativo');
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_type t
        JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE t.typname = 'tipo_operacion_enum'
          AND n.nspname = 'woolfandfox'
    ) THEN
        CREATE TYPE woolfandfox.tipo_operacion_enum AS ENUM ('Entrega', 'Recogida');
    END IF;
END $$;

-- Tabla de roles operativos
CREATE TABLE IF NOT EXISTS woolfandfox.roles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol text NOT NULL UNIQUE,
    CONSTRAINT roles_nombre_rol_chk CHECK (nombre_rol IN ('Conductor', 'Ayudante', 'Andarín'))
);

-- Tabla de personal operativo
CREATE TABLE IF NOT EXISTS woolfandfox.personal (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    nombre text NOT NULL,
    rol_id integer NOT NULL,
    CONSTRAINT personal_rol_fk
        FOREIGN KEY (rol_id)
        REFERENCES woolfandfox.roles (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- Tabla de vehículos
CREATE TABLE IF NOT EXISTS woolfandfox.vehiculos (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    matricula text NOT NULL UNIQUE,
    CONSTRAINT vehiculos_matricula_chk CHECK (btrim(matricula) <> '')
);

-- Tabla de usuarios del sistema
CREATE TABLE IF NOT EXISTS woolfandfox.usuarios (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    username text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    nombre text NOT NULL,
    rol_sistema woolfandfox.rol_sistema_enum NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    creado_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT usuarios_username_chk CHECK (btrim(username) <> ''),
    CONSTRAINT usuarios_nombre_chk CHECK (btrim(nombre) <> '')
);

-- Tabla de rutas
CREATE TABLE IF NOT EXISTS woolfandfox.rutas (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    codigo_ruta text NOT NULL,
    fecha date NOT NULL,
    vehiculo_id uuid NOT NULL,
    reembolso_total numeric(12,2) NOT NULL DEFAULT 0,
    comentarios_percances text,
    confirmado_por uuid NOT NULL,
    foto_cierre_url text NOT NULL,
    hora_cierre timestamptz NOT NULL,
    CONSTRAINT rutas_vehiculo_fk
        FOREIGN KEY (vehiculo_id)
        REFERENCES woolfandfox.vehiculos (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT rutas_confirmado_por_fk
        FOREIGN KEY (confirmado_por)
        REFERENCES woolfandfox.usuarios (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT rutas_codigo_chk CHECK (btrim(codigo_ruta) <> ''),
    CONSTRAINT rutas_reembolso_chk CHECK (reembolso_total >= 0),
    CONSTRAINT rutas_foto_url_chk CHECK (btrim(foto_cierre_url) <> ''),
    CONSTRAINT rutas_codigo_fecha_uk UNIQUE (codigo_ruta, fecha)
);

-- Tabla pivote de asignación de personal a rutas
CREATE TABLE IF NOT EXISTS woolfandfox.asignacion_personal (
    ruta_id uuid NOT NULL,
    personal_id uuid NOT NULL,
    PRIMARY KEY (ruta_id, personal_id),
    CONSTRAINT asignacion_personal_ruta_fk
        FOREIGN KEY (ruta_id)
        REFERENCES woolfandfox.rutas (id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT asignacion_personal_personal_fk
        FOREIGN KEY (personal_id)
        REFERENCES woolfandfox.personal (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- Tabla de operaciones diarias por ruta
CREATE TABLE IF NOT EXISTS woolfandfox.operaciones_diarias (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    ruta_id uuid NOT NULL,
    tipo_operacion woolfandfox.tipo_operacion_enum NOT NULL,
    exitosas integer NOT NULL,
    incidencias integer NOT NULL,
    total integer NOT NULL,
    CONSTRAINT operaciones_diarias_ruta_fk
        FOREIGN KEY (ruta_id)
        REFERENCES woolfandfox.rutas (id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT operaciones_diarias_exitosas_chk CHECK (exitosas >= 0),
    CONSTRAINT operaciones_diarias_incidencias_chk CHECK (incidencias >= 0),
    CONSTRAINT operaciones_diarias_total_chk CHECK (total >= 0),
    CONSTRAINT operaciones_diarias_total_consistency_chk CHECK (total = exitosas + incidencias),
    CONSTRAINT operaciones_diarias_ruta_tipo_uk UNIQUE (ruta_id, tipo_operacion)
);

-- Índices para rendimiento de consultas de dashboard
CREATE INDEX IF NOT EXISTS idx_personal_rol_id ON woolfandfox.personal (rol_id);
CREATE INDEX IF NOT EXISTS idx_rutas_vehiculo_id ON woolfandfox.rutas (vehiculo_id);
CREATE INDEX IF NOT EXISTS idx_rutas_confirmado_por ON woolfandfox.rutas (confirmado_por);
CREATE INDEX IF NOT EXISTS idx_rutas_fecha ON woolfandfox.rutas (fecha DESC);
CREATE INDEX IF NOT EXISTS idx_asignacion_personal_personal_id ON woolfandfox.asignacion_personal (personal_id);
CREATE INDEX IF NOT EXISTS idx_operaciones_diarias_ruta_id ON woolfandfox.operaciones_diarias (ruta_id);
CREATE INDEX IF NOT EXISTS idx_operaciones_diarias_tipo ON woolfandfox.operaciones_diarias (tipo_operacion);

-- Datos base para los roles operativos
INSERT INTO woolfandfox.roles (nombre_rol)
VALUES
    ('Conductor'),
    ('Ayudante'),
    ('Andarín')
ON CONFLICT (nombre_rol) DO NOTHING;

-- Comentarios de esquema para documentación interna
COMMENT ON SCHEMA woolfandfox IS 'Esquema principal del sistema L-N-LOGISTIC';
COMMENT ON TABLE woolfandfox.usuarios IS 'Usuarios administrativos del sistema con autenticación por Auth.js';
COMMENT ON TABLE woolfandfox.rutas IS 'Cierres diarios de ruta con foto, reembolso y confirmación';
COMMENT ON TABLE woolfandfox.operaciones_diarias IS 'Resumen de entregas y recogidas por ruta';
COMMENT ON COLUMN woolfandfox.rutas.confirmado_por IS 'FK al usuario que registró el cierre — asignado desde la sesión del servidor (no editable por el cliente)';
